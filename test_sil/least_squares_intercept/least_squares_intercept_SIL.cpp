#include "python_control.hpp"

#include <pybind11/numpy.h>
#include <pybind11/pybind11.h>

namespace py = pybind11;

template <typename T>
using InputArray = py::array_t<T, py::array::c_style | py::array::forcecast>;

// Each generated model has a distinct type (precision, feature count, mode).
// Bind all cases in one module so no stale Python extension is reloaded.
template <typename Model>
void bind_model(py::module_ &module, const char *name, Model (*make)()) {
  using T = typename Model::Value_Type;
  module.def(name, [make](InputArray<T> x_in, InputArray<T> y_in) {
    if (x_in.ndim() != 2 ||
        x_in.shape(0) != static_cast<py::ssize_t>(Model::NUMBER_OF_DATA) ||
        x_in.shape(1) != static_cast<py::ssize_t>(Model::X_Type::COLS)) {
      throw py::value_error("X has the wrong shape for the generated model.");
    }
    if (y_in.ndim() != 2 ||
        y_in.shape(0) != static_cast<py::ssize_t>(Model::NUMBER_OF_DATA) ||
        y_in.shape(1) != 1) {
      throw py::value_error("y must have shape (number_of_data, 1).");
    }

    typename Model::X_Type x;
    typename Model::Y_Type y;
    const auto x_values = x_in.template unchecked<2>();
    const auto y_values = y_in.template unchecked<2>();
    for (std::size_t row = 0; row < Model::NUMBER_OF_DATA; ++row) {
      for (std::size_t col = 0; col < Model::X_Type::COLS; ++col) {
        x.unsafe_access(row, col) = x_values(row, col);
      }
      y.unsafe_access(row, 0) = y_values(row, 0);
    }

    auto model = make();
    model.fit(x, y);
    const auto weights = model.get_weights();
    const auto predicted = model.predict(x);
    typename Model::X_Type zeros;
    const auto zero_predicted = model.predict(zeros);

    py::array_t<T> weights_out({static_cast<py::ssize_t>(Model::PARAMETER_COUNT),
                               static_cast<py::ssize_t>(1)});
    py::array_t<T> predicted_out({static_cast<py::ssize_t>(Model::NUMBER_OF_DATA),
                                 static_cast<py::ssize_t>(1)});
    py::array_t<T> zero_out({static_cast<py::ssize_t>(Model::NUMBER_OF_DATA),
                            static_cast<py::ssize_t>(1)});
    for (std::size_t row = 0; row < Model::PARAMETER_COUNT; ++row) {
      weights_out.mutable_at(row, 0) = weights(row, 0);
    }
    for (std::size_t row = 0; row < Model::NUMBER_OF_DATA; ++row) {
      predicted_out.mutable_at(row, 0) = predicted(row, 0);
      zero_out.mutable_at(row, 0) = zero_predicted(row, 0);
    }
    return py::make_tuple(weights_out, predicted_out, zero_out);
  });
}

